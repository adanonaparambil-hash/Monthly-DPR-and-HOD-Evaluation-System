-- ─────────────────────────────────────────────────────────────────────────────
--  PART 2 — THE "ONCE" GUARD
--
--  A unique key, not a flag set after sending. The row is written BEFORE the
--  address is handed back, so a retried API call, a double-click or a replayed
--  request hits DUP_VAL_ON_INDEX and sends nothing. A flag updated after the
--  send would still allow a duplicate in the window between the two.
--
--  NOTIFY_KEY exists so later rules (a second watcher, a different trigger) can
--  share the table without colliding with this one.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE TS_EXIT_NOTIFY_LOG (
    LOG_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EXIT_ID      NUMBER        NOT NULL,
    NOTIFY_KEY   VARCHAR2(50)  NOT NULL,
    NOTIFY_EMPID VARCHAR2(50),
    SENT_ON      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_EXIT_NOTIFY_LOG PRIMARY KEY (LOG_ID)
);

CREATE UNIQUE INDEX UX_EXIT_NOTIFY_LOG
    ON TS_EXIT_NOTIFY_LOG (EXIT_ID, NOTIFY_KEY);


