-- ============================================================================
--  PROJECT-DEPARTMENT LEAVE NOTIFICATION
--  ---------------------------------------------------------------------------
--  When an employee of a watched (project) department files an exit/leave form
--  and their HOD APPROVES it, one e-mail goes to the watcher (ADS4811, RAJAN
--  PRABHAKARAN) — unless the watcher WAS the approving HOD, in which case he
--  already knows.
--
--  Agreed behaviour:
--    * all three form types — Emergency, Planned, Resignation
--    * a form with no HOD step (Worker) sends nothing
--    * e-mail only, no in-app bell notification
--
--  RUN THE PARTS IN ORDER. Part 4 (the e-mail template) must exist BEFORE the
--  procedure goes live: the procedure marks the notification as sent, so if the
--  template is missing when the first form is approved, that one form is logged
--  and never mailed.
-- ============================================================================


-- ─────────────────────────────────────────────────────────────────────────────
--  PART 1 — WHO IS WATCHED, AND BY WHOM
--
--  This is a TABLE and not an IN-list in the procedure, because the department
--  names are not stable. Checked against TM_DPR_EMPLOYEE_DETAILS:
--    'DESIGN & BUILDS'    matches 0 rows — the real one is 'DESIGN & BUILD'
--    'PROJECTS - CIVIL', 'Projects - CIVIL', 'PROJECTS CIVIL - IN'
--                         are 1 employee each — typo variants of PROJECTS-CIVIL
--    'SITE'               1,998 rows overall but only 2 active
--  Matching is UPPER(TRIM(...)) on both sides, so every variant above still
--  hits, and a new spelling is one INSERT rather than a procedure change.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE TM_EXIT_DEPT_NOTIFY (
    NOTIFY_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DEPARTMENT   VARCHAR2(200) NOT NULL,
    NOTIFY_EMPID VARCHAR2(50)  NOT NULL,          -- who gets told
    TRIGGER_ROLE VARCHAR2(50)  DEFAULT 'HOD' NOT NULL,
    FORM_TYPES   VARCHAR2(20),                    -- NULL = every form type
    IS_ACTIVE    CHAR(1)       DEFAULT 'Y'  NOT NULL,
    CREATED_ON   DATE          DEFAULT SYSDATE,
    CREATED_BY   VARCHAR2(50),
    CONSTRAINT PK_EXIT_DEPT_NOTIFY PRIMARY KEY (NOTIFY_ID)
);

-- one rule per department + watcher + trigger, regardless of how it is spelled
CREATE UNIQUE INDEX UX_EXIT_DEPT_NOTIFY
    ON TM_EXIT_DEPT_NOTIFY (UPPER(TRIM(DEPARTMENT)), NOTIFY_EMPID, TRIGGER_ROLE);

-- FORM_TYPES left NULL = E, P and R all trigger.
--
-- Two things this statement has to survive, and a plain INSERT ... SELECT of
-- the raw list does not:
--
--  1) The list contains the SAME department twice in different case —
--     'PROJECTS - CIVIL' and 'Projects - CIVIL'. The unique index is on
--     UPPER(TRIM(DEPARTMENT)), so those are one key and the insert fails with
--     ORA-00001. GROUP BY UPPER(TRIM(...)) collapses them to one row, and will
--     do the same for any case variant added to the list later.
--
--  2) It is re-runnable. NOT EXISTS means running it twice, or adding a
--     department to the list and running it again, inserts only what is
--     missing instead of failing on what is already there.
INSERT INTO TM_EXIT_DEPT_NOTIFY (DEPARTMENT, NOTIFY_EMPID, CREATED_BY)
SELECT s.dept, 'ADS4811', 'SETUP'
  FROM (SELECT MIN(COLUMN_VALUE) AS dept
          FROM TABLE(SYS.ODCIVARCHAR2LIST(
                'PROJECTS CIVIL - IN',
                'PROJECTS - CIVIL',    -- 'Projects - CIVIL' is the same key, dropped
                'PROJECTS - INFRA',
                'PROJECTS-CIVIL',
                'PROJECTS-MECHANICAL',
                'PROJECTS',
                'PROJECTS-ELECTRICAL',
                'CIVIL',
                'DESIGN & BUILD',      -- 'DESIGN & BUILDS' in the original list matches nothing
                'SITE',
                'INFRASTRUCTURE',
                'ARCHITECH',
                'BIM',
                'PLANNING',
                'POST TENSION',
                'TECHNICAL',
                'QS',
                'QS & TENDERING',
                'QS PRE TENDER',
                'QS POST TENDER',
                'CONTRACTS',
                'HSE',
                'HSE Q',
                'QUALITY ASSURANCE & QUALITY CONTROL',
                'PMV',
                'CWS',
                'CWH'))
         GROUP BY UPPER(TRIM(COLUMN_VALUE))) s
 WHERE NOT EXISTS (SELECT 1
                     FROM TM_EXIT_DEPT_NOTIFY t
                    WHERE UPPER(TRIM(t.DEPARTMENT)) = UPPER(TRIM(s.dept))
                      AND t.NOTIFY_EMPID = 'ADS4811'
                      AND TRIM(t.TRIGGER_ROLE) = 'HOD');

COMMIT;

