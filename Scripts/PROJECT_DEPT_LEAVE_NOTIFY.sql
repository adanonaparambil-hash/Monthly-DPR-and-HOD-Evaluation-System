-- ─────────────────────────────────────────────────────────────────────────────
--  PART 5 — PACKAGE BODY
--
--  Only ONE block is added, between the existing p_app_id block and the
--  "IF p_ISFinalStage = 'N' THEN OPEN p_cursor" block. Nothing else changes.
--
--  It must sit there and not lower down: the existing
--      IF p_next_level IS NULL THEN ... RETURN; END IF;
--  leaves the procedure early once nothing is pending, and an HOD approval on a
--  short chain can be exactly that case.
--
--  Add these three declarations to the IS section, beside v_created_by:
--
--      v_act_role     VARCHAR2(50);
--      v_act_status   VARCHAR2(10);
--      v_act_approver VARCHAR2(50);
--      v_watcher      VARCHAR2(50);
-- ─────────────────────────────────────────────────────────────────────────────

    /* ── project-department watch notification ────────────────────────────
       Whole block is wrapped in its own handler. Anything that goes wrong in
       here — a missing table, a bad row, a duplicate — must leave the three
       OUT params NULL and let the approval flow carry on. A notification is
       never worth failing an approval over.                                */
    BEGIN
        p_notify_empid := NULL;
        p_notify_name  := NULL;
        p_notify_email := NULL;

        IF p_app_id IS NOT NULL THEN

            -- what was just acted on
            SELECT TRIM(APPROVER_ROLE), TRIM(APPROVAL_STATUS), TRIM(APPROVER_ID)
              INTO v_act_role, v_act_status, v_act_approver
              FROM TS_EMP_EXIT_APPROVAL
             WHERE APPROVAL_ID = p_app_id;

            -- only an HOD APPROVAL fires this. A Worker form has no HOD step,
            -- so it never gets here — which is the agreed behaviour.
            IF v_act_role = 'HOD' AND v_act_status = 'A' THEN

                -- watched department? and is the watcher someone OTHER than
                -- the HOD who just approved? If the watcher IS that HOD, no row
                -- comes back and nothing is sent — he already knows.
                SELECT TRIM(r.NOTIFY_EMPID)
                  INTO v_watcher
                  FROM TM_EXIT_DEPT_NOTIFY r
                 WHERE r.IS_ACTIVE = 'Y'
                   AND TRIM(r.TRIGGER_ROLE) = 'HOD'
                   AND UPPER(TRIM(r.DEPARTMENT)) = UPPER(TRIM(p_submitted_department))
                   AND (r.FORM_TYPES IS NULL
                        OR INSTR(','||UPPER(REPLACE(r.FORM_TYPES,' ',''))||',',
                                 ','||UPPER(TRIM(p_leavetype))||',') > 0)
                   AND TRIM(r.NOTIFY_EMPID) <> v_act_approver
                 FETCH FIRST ROW ONLY;

                -- address first: no point logging a send we cannot make
                SELECT d.EMPLOYEENAME, d.EMAIL
                  INTO p_notify_name, p_notify_email
                  FROM TM_DPR_EMPLOYEE_DETAILS d
                 WHERE d.EMPID = v_watcher;

                IF p_notify_email IS NULL THEN
                    p_notify_name := NULL;
                ELSE
                    -- claim it. The unique key is what makes this once-only;
                    -- a second call raises DUP_VAL_ON_INDEX and falls into the
                    -- handler below with the OUT params cleared.
                    INSERT INTO TS_EXIT_NOTIFY_LOG (EXIT_ID, NOTIFY_KEY, NOTIFY_EMPID)
                    VALUES (p_exit_id, 'PROJECT_HEAD_LEAVE', v_watcher);

                    -- committed here and not at the end of the procedure: the
                    -- early RETURN below never reaches that COMMIT, and an
                    -- uncommitted claim would be rolled back when the caller
                    -- closes the connection — letting a retry send twice.
                    COMMIT;

                    p_notify_empid := v_watcher;
                END IF;

            END IF;
        END IF;

    EXCEPTION
        WHEN OTHERS THEN            -- includes NO_DATA_FOUND and DUP_VAL_ON_INDEX
            p_notify_empid := NULL;
            p_notify_name  := NULL;
            p_notify_email := NULL;
    END;
    /* ── end of the added block ─────────────────────────────────────────── */


